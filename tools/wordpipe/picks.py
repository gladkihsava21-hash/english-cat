def picturable_words(all_words):
    """Слова из базы, для которых заведён заголовок статьи.

    all_words — множество/список слов базы. Возвращает список пар
    (слово, кортеж заголовков) в порядке базы, чтобы отчёт читался ровно.
    """
    known = set(all_words)
    return [(w, titles) for w, titles in PICKS.items() if w in known]
