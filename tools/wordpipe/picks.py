def picturable_words(all_words):
    """Слова из базы, для которых заведён заголовок статьи.

    Ручной PICKS плюс автоматический AUTO_PICKS (tools/expand_picks.py —
    заголовок совпал со словом, а русская интервики с переводом). Ручной
    главнее: там уточнённые заголовки. NO_PHOTO и REVIEW выкидываются
    из обоих. Порядок — по алфавиту, чтобы отчёт читался ровно.
    """
    try:
        from .picks_auto import AUTO_PICKS
    except ImportError:      # авто-списка может не быть — это не ошибка
        AUTO_PICKS = {}
    try:
        from .picks_auto2 import AUTO_PICKS2   # Викиданные P18
    except ImportError:
        AUTO_PICKS2 = {}
    merged = dict(AUTO_PICKS2)
    merged.update(AUTO_PICKS)
    merged.update(PICKS)
    for w in set(NO_PHOTO) | set(REVIEW):
        merged.pop(w, None)
    known = set(all_words)
    return sorted((w, t) for w, t in merged.items() if w in known)
